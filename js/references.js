export function initReferences() {
  const list = document.getElementById('referencesList');
  if (!list) return;

  REFS.forEach((ref) => {
    const li = document.createElement('li');
    li.className = 'reference-item';
    li.id = 'ref-' + ref.key;

    li.appendChild(document.createTextNode(ref.authors + ' (' + ref.year + '). ' + ref.title + '. '));

    const em = document.createElement('em');
    em.textContent = ref.journal;
    li.appendChild(em);

    li.appendChild(document.createTextNode(', ' + ref.details + '. '));

    const link = document.createElement('a');
    link.href = ref.href;
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    link.textContent = ref.href;
    li.appendChild(link);

    list.appendChild(li);
  });
}
